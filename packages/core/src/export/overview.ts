// The richer export's own tabs: Overview (key numbers + charts), Vesting by month, Missing documents.
// Numbers come from the same engine as the app's cap table, What's missing list and vesting graph.
import { computeGaps } from "../gaps";
import { ratioFixed } from "../num";
import { isFounder } from "../rows";
import { vestingSchedule } from "../schedule";
import type { Row, State } from "../types";
import type { Cell, Chart, Sheet } from "./sheets";

const pct = (part: bigint, whole: bigint): Cell =>
  whole > 0n ? { pct: ratioFixed(part, whole, 8).replace(/\.?0+$/, "") || "0" } : "";
const head = (company: string, title: string, asOf: string, columns: string[]): Cell[][] => [
  [`${company} ${title}`],
  [`Generated by Capfolder, data to ${asOf}`],
  [],
  columns,
];
/** Excel column letters for a 0-based index (0 → A, 26 → AA). */
const col = (i: number): string =>
  (i < 26 ? "" : col(Math.floor(i / 26) - 1)) + String.fromCharCode(65 + (i % 26));
const MONTH = (iso: string) => iso.slice(0, 7);
/** Every "YYYY-MM" from `from` to `to`, inclusive. */
function months(from: string, to: string): string[] {
  const out: string[] = [];
  let [y, m] = from.split("-").map(Number) as [number, number];
  for (let k = from; k <= to; k = `${y}-${String(m).padStart(2, "0")}`) {
    out.push(k);
    [y, m] = m === 12 ? [y + 1, 1] : [y, m + 1];
  }
  return out;
}

export function overviewTabs(
  s: State,
  rows: Row[],
  t: { fullyDiluted: bigint; poolAvailable: bigint; safeAmount: string },
  company: string,
  asOf: string,
  cur: string,
): { overview: Sheet; vesting: Sheet; missing: Sheet } {
  const fd = t.fullyDiluted;
  const fdRows = rows.filter((r) => r.group <= 2 && (r.shares ?? 0n) > 0n);
  const founders = fdRows
    .filter((r) => isFounder(s, s.securities.get(r.securityId)))
    .reduce((a, r) => a + (r.shares ?? 0n), 0n);

  // Vesting by month: one row per grant with a schedule, cumulative vested at the end of each month.
  const grants = [...s.securities.values()]
    .filter((x) => x.kind !== "convertible")
    .map((x) => ({ x, pts: vestingSchedule(x, s) }))
    .filter((g): g is { x: typeof g.x; pts: NonNullable<typeof g.pts> } => !!g.pts?.length)
    .sort((a, b) => (a.x.date < b.x.date ? -1 : a.x.date > b.x.date ? 1 : a.x.id < b.x.id ? -1 : 1));
  const span = grants.length
    ? months(
        grants.map((g) => MONTH(g.x.vestingStart?.date ?? g.pts[0]!.date)).sort()[0]!,
        grants
          .map((g) => MONTH(g.pts.at(-1)!.date))
          .sort()
          .at(-1)!,
      )
    : [];
  const at = (pts: { date: string; cumulative: bigint }[], m: string) =>
    pts.filter((p) => MONTH(p.date) <= m).at(-1)?.cumulative ?? 0n;
  const name = (id: string) => String(s.stakeholders.get(id)?.name?.legal_name ?? id);
  const vRows = head(company, "Vesting by month", asOf, ["Holder", "Security", ...span]);
  for (const g of grants) vRows.push([name(g.x.stakeholderId), g.x.id, ...span.map((m) => at(g.pts, m))]);
  const totals = span.map((m) => grants.reduce((a, g) => a + at(g.pts, m), 0n));
  if (grants.length) vRows.push(["Total", "", ...totals]);
  const vesting: Sheet = { name: "Vesting by month", rows: vRows, header: [3, vRows.length - 1], freeze: 4 };

  const missing: Sheet = {
    name: "Missing documents",
    rows: [
      ...head(company, "Missing documents", asOf, ["What's missing", "Priority"]),
      ...computeGaps(s).map((g): Cell[] => [g.text, g.severity === "red" ? "High" : "Medium"]),
    ],
    header: [3],
    freeze: 4,
  };

  // Overview: key numbers, then ownership by holder (each shareholder, options together, the pool).
  const own = new Map<string, bigint>();
  for (const r of fdRows) {
    const k =
      r.group === 0 ? r.stakeholder : r.group === 1 ? "Employees (options)" : "Option pool (available)";
    own.set(k, (own.get(k) ?? 0n) + (r.shares ?? 0n));
  }
  const oRows = head(company, "Overview", asOf, ["Key number", "Value"]);
  oRows.push(
    ["Fully diluted", fd],
    ["Founders", pct(founders, fd)],
    ["Option pool available", t.poolAvailable],
    [
      `SAFEs outstanding (${cur})`,
      /^\d+$/.test(t.safeAmount) ? BigInt(t.safeAmount) : t.safeAmount ? { num: t.safeAmount } : "",
    ],
    [],
  );
  const ownHead = oRows.length;
  oRows.push(["Ownership, fully diluted", "Shares", "%"]);
  for (const [k, v] of own) oRows.push([k, v, pct(v, fd)]);
  const ownEnd = oRows.length; // 1-based row of the last holder
  oRows.push([], ["Vesting by month is on its own tab. Not legal, tax or financial advice."]);

  const charts: Chart[] = [];
  if (own.size)
    charts.push({
      kind: "doughnut",
      title: "Ownership, fully diluted",
      series: "Shares",
      cat: { ref: `'Overview'!$A$${ownHead + 2}:$A$${ownEnd}`, values: [...own.keys()] },
      val: { ref: `'Overview'!$B$${ownHead + 2}:$B$${ownEnd}`, values: [...own.values()].map(String) },
      at: { col: 4, row: 3, cols: 8, rows: 16 },
    });
  if (span.length)
    charts.push({
      kind: "line",
      title: "Vested over time (shares)",
      series: "Vested shares",
      cat: { ref: `'Vesting by month'!$C$4:$${col(span.length + 1)}$4`, values: span },
      val: {
        ref: `'Vesting by month'!$C$${vRows.length}:$${col(span.length + 1)}$${vRows.length}`,
        values: totals.map(String),
      },
      at: { col: 4, row: 20, cols: 8, rows: 16 },
    });
  const overview: Sheet = { name: "Overview", rows: oRows, header: [3, ownHead], freeze: 4, charts };
  return { overview, vesting, missing };
}
