// Precompiles the OCF validators so the app never needs eval / new Function (the desktop CSP forbids 'unsafe-eval').
// Run after changing the schemas or ajv: pnpm --filter @capfolder/core gen:ocf
import { readFileSync, writeFileSync } from "node:fs";
import Ajv from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const dir = new URL("../src/ocf/", import.meta.url);
const docs = JSON.parse(readFileSync(new URL("schemas-1.2.0.json", dir), "utf8"));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
for (const s of docs) ajv.addSchema(s);
const exports = {};
for (const s of docs) {
  if (s.$id.includes("/primitives/")) continue;
  // Equity-comp transactions use an enum (current name + deprecated TX_PLAN_SECURITY_* alias) instead of a const.
  const ot = s.properties?.object_type;
  const ft = s.properties?.file_type?.const;
  for (const key of ft ? [ft] : ot?.const ? [ot.const] : (ot?.enum ?? [])) exports[key] = s.$id;
}
// ajv's esm mode still emits require() for its runtime helpers and formats: import them and recover module.exports
// (Node puts it on .default; Vite/Vitest spread it onto the namespace when the module sets __esModule).
const mods = [];
const code = standalone(ajv, exports).replace(/require\("([^"]+)"\)/g, (_, m) => {
  if (!mods.includes(m)) mods.push(m);
  return `__m${mods.indexOf(m)}`;
});
const imports = mods
  .map(
    (m, i) =>
      `import * as __i${i} from "${m}.js";\nconst __m${i} = typeof __i${i}.default === "object" ? __i${i}.default : __i${i};`,
  )
  .join("\n");
writeFileSync(
  new URL("validators.gen.js", dir),
  `// @ts-nocheck\n// Generated by scripts/gen-ocf-validators.mjs. Do not edit.\n${imports}\n${code}`,
);
