// F-29: the full cap table workbook, laid out like the exports lawyers and investors already know (Pulley/Carta).
import { strFromU8, unzipSync } from "fflate";
import { describe, expect, test } from "vitest";
import { fullCapTable, holdingsCsv } from "../src/export/full";
import type { Cell, Sheet } from "../src/export/sheets";
import { toXlsx } from "../src/export/xlsx";
import { readXlsx } from "../src/import/xlsx-read";
import { reduce } from "../src/reduce";
import { capTableRows } from "../src/rows";
import { capTableTotals } from "../src/totals";
import { acmeEvents } from "./helpers";

const AS_OF = "2026-10-07";
const base = acmeEvents();
const book = fullCapTable(base, AS_OF);
const text = (c: Cell) =>
  c === null ? "" : typeof c === "object" ? ("num" in c ? c.num : "pct" in c ? c.pct : c.date) : String(c);
const tab = (name: string, b: Sheet[] = book) => b.find((s) => s.name === name)!;
const rowOf = (s: Sheet, first: string) => s.rows.find((r) => text(r[0] ?? null) === first)?.map(text);
const col = (s: Sheet, header: string) => s.rows[3]!.map(text).indexOf(header);

describe("full cap table workbook", () => {
  test("Pulley's tabs: summary, ownership, a ledger per class and per plan, convertibles, voting", () =>
    expect(book.map((s) => s.name)).toEqual([
      "Summary",
      "Ownership",
      "Common (CS) Ledger",
      "2025 Equity Incentive Plan Ledger",
      "Convertibles",
      "Voting Ownership",
      "All holdings",
    ]));

  test("title rows, then the header on row 4, frozen", () => {
    for (const s of book.filter((x) => x.name !== "All holdings")) {
      expect(text(s.rows[0]![0]!)).toMatch(/^Acme/);
      expect(text(s.rows[1]![0]!)).toBe(`Generated by Capfolder, data to ${AS_OF}`);
      expect(s.freeze).toBe(4);
    }
    expect(text(tab("Summary").rows[0]![0]!)).toMatch(/Summary Capitalization Table$/);
  });

  test("ledger columns match what lawyers expect, even the ones Capfolder leaves empty", () => {
    expect(tab("Common (CS) Ledger").rows[3]!.map(text).slice(0, 12)).toEqual([
      "Certificate ID",
      "Stakeholder Name",
      "Stakeholder External ID",
      "Issue Date",
      "Shares Issued",
      "Shares Outstanding",
      "Price Per Share",
      "Vesting Start Date",
      "Vesting Schedule",
      "Shares Vested",
      "Shares Unvested",
      "Capital Contribution",
    ]);
    expect(tab("Convertibles").rows[3]!.map(text)).toContain("Valuation Cap");
    expect(tab("2025 Equity Incentive Plan Ledger").rows[3]!.map(text)).toContain("Expiration Date");
    const cs = tab("Common (CS) Ledger");
    const mads = rowOf(cs, "CS-1")!;
    expect(mads[col(cs, "Stakeholder Name")]).toBe("Mads Petersen");
    expect(mads[col(cs, "Shares Outstanding")]).toBe("4000000");
    expect(mads[col(cs, "Shares Vested")]).toBe("3000000");
    expect(mads[col(cs, "Vesting Schedule")]).toBe("48 months, 12-month cliff, monthly thereafter");
    expect(mads[col(cs, "Debt Cancelled")]).toBe(""); // OCF has no field for it
  });

  test("totals equal the engine's numbers", () => {
    const fd = capTableTotals(capTableRows(reduce(base, AS_OF))).fullyDiluted.toString();
    expect(fd).toBe("8000000");
    expect(rowOf(tab("Summary"), "Total Fully Diluted Shares")).toContain(fd);
    const own = tab("Ownership");
    expect(rowOf(own, "Total")![col(own, "Fully Diluted")]).toBe(fd);
    expect(rowOf(own, "Total")![col(own, "Issued and Outstanding")]).toBe("7000000");
    const cs = tab("Common (CS) Ledger");
    expect(rowOf(cs, "Total")![col(cs, "Shares Outstanding")]).toBe("7000000");
    const plan = tab("2025 Equity Incentive Plan Ledger");
    expect(rowOf(plan, "Total")![col(plan, "Outstanding")]).toBe("80000");
    expect(rowOf(plan, "Available for Issuance")).toContain("920000");
    const cv = tab("Convertibles");
    expect(rowOf(cv, "Total")![col(cv, "Principal Outstanding")]).toBe("900000");
    expect(rowOf(tab("Voting Ownership"), "Totals")).toContain("7000000");
  });

  test("percentages are fractions (formatted as %), dates are dates", () => {
    const own = tab("Ownership");
    const mads = own.rows.find((r) => text(r[0] ?? null) === "Mads Petersen")!;
    expect(mads[col(own, "Fully Diluted % Ownership")]).toEqual({ pct: "0.5" });
    const cs = tab("Common (CS) Ledger");
    expect(
      rowOf(cs, "CS-1") && cs.rows.find((r) => text(r[0] ?? null) === "CS-1")![col(cs, "Issue Date")],
    ).toEqual({ date: "2021-09-14" });
  });

  test("as of a past date: no plan yet, no options", () => {
    const past = fullCapTable(base, "2025-01-01");
    expect(past.map((s) => s.name)).not.toContain("2025 Equity Incentive Plan Ledger");
    expect(rowOf(tab("Summary", past), "Total Fully Diluted Shares")).toContain("7000000");
  });

  test("xlsx: every tab, a frozen header, % and date formats", () => {
    const bytes = toXlsx(book);
    expect(readXlsx(bytes).map((s) => s.name)).toEqual(book.map((s) => s.name.slice(0, 31)));
    expect(readXlsx(bytes).every((s) => s.rows.length > 0)).toBe(true);
    const files = unzipSync(bytes);
    const sheet2 = strFromU8(files["xl/worksheets/sheet2.xml"]!);
    expect(sheet2).toContain('<pane ySplit="4" topLeftCell="A5" activePane="bottomLeft" state="frozen"/>');
    const styles = strFromU8(files["xl/styles.xml"]!);
    expect(styles).toContain('numFmtId="10"'); // 0.00%
    expect(styles).toContain('formatCode="yyyy-mm-dd"');
  });
});

test("long sheet names stay unique after Excel's 31-character cut, and lose characters Excel refuses", () => {
  const long = { name: "A very long equity incentive plan name: Ledger", rows: [], header: [] };
  expect(readXlsx(toXlsx([long, long])).map((s) => s.name)).toEqual([
    "A very long equity incentive pl",
    "A very long equity incentive 2",
  ]);
});

describe("holdings CSV", () => {
  test("one row per security with the full ledger columns; numbers stay plain", () => {
    const lines = holdingsCsv(base, AS_OF).trim().split("\n");
    expect(lines[0]).toMatch(/^Security ID,Stakeholder,Stakeholder Type,Kind,Class or Plan,Issue Date,/);
    expect(lines).toHaveLength(1 + 7); // 2 common, 2 options, 3 SAFEs
    expect(lines.find((l) => l.startsWith("OPT-1,"))).toContain(",2035-10-07,");
    expect(lines.find((l) => l.startsWith("CS-1,"))).toContain(",4000000,");
  });
});

test("a number cell holding anything but a number is written as plain text, never as XML or a formula", () => {
  const evil = '1</v><f>HYPERLINK("http://x","y")</f><v>2';
  const xml = strFromU8(
    unzipSync(toXlsx([{ name: "S", rows: [[{ num: evil }, { pct: evil }, { num: "-12.5" }]], header: [] }]))[
      "xl/worksheets/sheet1.xml"
    ]!,
  );
  expect(xml).not.toContain("<f>");
  expect(xml).toContain("&lt;/v&gt;&lt;f&gt;");
  expect(xml).toContain("<v>-12.5</v>");
});
